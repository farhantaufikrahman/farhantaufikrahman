def obj_constellation(cx, cy, accent):
    pts = [(-120, 40), (-60, -50), (0, 10), (70, -60), (120, 30), (40, 70)]
    lines = "".join(
        f'<path d="M{cx + a[0]} {cy + a[1]}L{cx + b[0]} {cy + b[1]}" stroke="{accent}" stroke-opacity=".45" '
        f'stroke-width="2" stroke-dasharray="2 6"/>'
        for a, b in zip(pts, pts[1:])
    )
    stars = "".join(
        f'<g class="t{i % 4 + 1}" style="animation-delay:-{i * .7:.1f}s">{pixel_star(cx + x, cy + y, 2, accent, "#fff")}</g>'
        for i, (x, y) in enumerate(pts)
    )
    return (
        '<style>.flash{animation:flash 4s steps(6) infinite;transform-box:fill-box;transform-origin:center}'
        '@keyframes flash{0%,70%,100%{transform:scale(1)}80%{transform:scale(1.35)}}</style>'
        + lines + stars + f'<g class="flash">{pixel_star(cx, cy + 10, 6, accent, "#fff")}</g>'
    )


