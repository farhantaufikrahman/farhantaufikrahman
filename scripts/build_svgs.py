def typewriter(x: float, y: float, phrases: list[str], size: float = 22, cycle: float = 20.0):
    """Monospace typewriter that cycles through phrases.

    textLength pins every glyph to the same cell width, so steps(n) reveals
    exactly one character per step whatever monospace font the viewer has.
    """
    cw = size * 0.6
    css, body = [], []
    slot = 100 / len(phrases)
    for i, p in enumerate(phrases):
        n = len(p)
        w = n * cw
        a, b = i * slot, (i + 1) * slot
        type_end = a + slot * 0.36
        hold_end = a + slot * 0.86
        erase_end = a + slot * 0.97
        css.append(
            f"@keyframes ty{i}{{0%,{a:.2f}%{{transform:scaleX(0)}}"
            f"{a:.2f}%{{transform:scaleX(0);animation-timing-function:steps({n},end)}}"
            f"{type_end:.2f}%,{hold_end:.2f}%{{transform:scaleX(1);animation-timing-function:steps({n},end)}}"
            f"{erase_end:.2f}%,100%{{transform:scaleX(0)}}}}"
            f"@keyframes cu{i}{{0%,{a:.2f}%{{opacity:0;transform:translateX(0)}}"
            f"{a+0.01:.2f}%{{opacity:1;transform:translateX(0);animation-timing-function:steps({n},end)}}"
            f"{type_end:.2f}%,{hold_end:.2f}%{{opacity:1;transform:translateX({w:.1f}px);animation-timing-function:steps({n},end)}}"
            f"{erase_end:.2f}%{{opacity:1;transform:translateX(0)}}{min(b, 99.99):.2f}%,100%{{opacity:0}}}}"
            f".ty{i}{{animation:ty{i} {cycle}s infinite;transform-box:fill-box;transform-origin:left}}"
            f".cu{i}{{animation:cu{i} {cycle}s infinite}}"
        )
        body.append(
            f'<clipPath id="tc{i}"><rect class="ty{i}" x="{x}" y="{y - size}" width="{w:.1f}" '
            f'height="{size * 1.4}"/></clipPath>'
            f'<g class="p{i}"><text clip-path="url(#tc{i})" x="{x}" y="{y}" font-family="ui-monospace,Menlo,Consolas,monospace" '
            f'font-size="{size}" fill="{INK_SOFT}" textLength="{w:.1f}" lengthAdjust="spacingAndGlyphs">{esc(p)}</text>'
            f'<g class="cu{i}"><rect class="blink" x="{x + 2}" y="{y - size * 0.82:.1f}" width="{cw * 0.75:.1f}" '
            f'height="{size * 0.95:.1f}" fill="{AMBER}"/></g></g>'
        )
    css.append("@media (prefers-reduced-motion:reduce){.p1,.p2,.p3,.cu0{display:none}.p0 text{clip-path:none}}")
    return "".join(css), "".join(body)


