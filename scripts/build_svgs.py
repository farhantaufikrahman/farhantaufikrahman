def chip_row(x, y, items, accent, size=18, h=30, gap=10, max_x=760):
    out, cx = [], x
    for it in items:
        w = text_width(it, size) + 24
        if cx + w > max_x:
            break
        out.append(
            f'<path d="{pixel_chip(cx, y, w, h, 4)}" fill="{PANEL}" stroke="{accent}" stroke-opacity=".45" stroke-width="2"/>'
            f'<text x="{cx + w / 2:.1f}" y="{y + h - 9}" font-size="{size}" fill="{INK_SOFT}" text-anchor="middle">{esc(it)}</text>'
        )
        cx += w + gap
    return "".join(out)


