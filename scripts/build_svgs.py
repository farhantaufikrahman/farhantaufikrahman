def logo(name: str, x: float, y: float, s: float) -> str:
    f = LOGO_FILE.get(name)
    if not f or not (LOGOS / f"{f}.svg").exists():
        return f'<text x="{x + s / 2}" y="{y + s - 4}" font-size="{s}" fill="{AMBER}" text-anchor="middle">{esc(name[:1])}</text>'
    data = base64.b64encode((LOGOS / f"{f}.svg").read_bytes()).decode()
    return f'<image href="data:image/svg+xml;base64,{data}" x="{x}" y="{y}" width="{s}" height="{s}"/>'


